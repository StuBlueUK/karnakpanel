#!/usr/bin/env bash
# phpbb-install.sh <domain> <owner> <subdir> <db> <dbuser> <dbpass> <title> <user_id> <domain_id> <url>
# One-click phpBB (pinned 3.3.19) into a docroot subdir. Finish via the web
# installer (database page comes pre-filled from config.php — just continue).
# Same contract/guards as wp-install.sh: DETACHED background, tracking rows on
# success, refuses to clobber, dbpass must be panel-generated hex.
set -euo pipefail
. "$(dirname "$(readlink -f "$0")")/secret-args.sh"; secret_argv "$@"; set -- "${SECRET_ARGV[@]}"  # @stdin secrets
. "$(dirname "$(readlink -f "$0")")/db-caps.sh"  # DB_CAPS: per-user MariaDB caps (admin-set)
D="${1:?}"; U="${2:?}"; SUB="${3:-}"; DB="${4:?}"; DBU="${5:?}"; DBP="${6:?}"; TITLE="${7:-phpBB}"
UIDN="${8:?}"; DID="${9:?}"; URL="${10:?}"
LOG="/var/log/karnakpanel/software.log"
VER="3.3.19"
( exec >>"$LOG" 2>&1
  echo "=== $(date -Is) phpbb install for $D${SUB:+/$SUB} ==="
  [[ "$D" =~ ^[a-z0-9.-]+\.[a-z]{2,}$ ]] || { echo "bad domain"; exit 1; }
  [[ "$U" =~ ^[a-z][a-z0-9_]{2,31}$ ]] || { echo "bad owner"; exit 1; }
  [[ "$SUB" =~ ^[a-zA-Z0-9_-]{0,64}$ ]] || { echo "bad subdir"; exit 1; }
  [[ "$DB" =~ ^[a-z][a-z0-9_]{2,63}$ ]] || { echo "bad db"; exit 1; }
  [[ "$DBU" =~ ^[a-z][a-z0-9_]{2,31}$ ]] || { echo "bad dbuser"; exit 1; }
  [[ "$DBP" =~ ^[a-f0-9]{12,64}$ ]] || { echo "db password must be panel-generated hex"; exit 1; }
  [[ "$UIDN" =~ ^[0-9]{1,10}$ && "$DID" =~ ^[0-9]{1,10}$ ]] || { echo "bad ids"; exit 1; }
  [[ "$URL" =~ ^https?://[a-z0-9.-]+\.[a-z]{2,}(/[a-z0-9_-]{1,64})?/?$ ]] || { echo "bad url"; exit 1; }
  id "$U" >/dev/null 2>&1 || { echo "no such user"; exit 1; }
  DOC="/home/$U/$D/public_html${SUB:+/$SUB}"
  [[ -d "/home/$U/$D/public_html" ]] || { echo "no docroot for $D (add the domain first)"; exit 1; }
  mkdir -p "$DOC"
  LEFT="$(ls -A "$DOC" | grep -v -e '^index\.html$' -e '^\.well-known$' -e '^autodiscover$' || true)"
  [[ -z "$LEFT" ]] || { echo "docroot not empty ($DOC) — refusing to overwrite"; exit 1; }
  rm -f "$DOC/index.html"
  TMP="$(mktemp -d)"
  trap 'rm -rf "$TMP"' EXIT
  command -v bzip2 >/dev/null 2>&1 || apt-get install -y bzip2 2>&1 | tail -1 || { echo "bzip2 missing"; exit 1; }
  curl -fsSL --max-time 180 "https://download.phpbb.com/pub/release/3.3/$VER/phpBB-$VER.tar.bz2" -o "$TMP/phpbb.tar.bz2" || { echo "download failed"; exit 1; }
  tar tjf "$TMP/phpbb.tar.bz2" > "$TMP/list.txt" || { echo "bad tarball"; exit 1; }
  grep -q '^phpBB3/' "$TMP/list.txt" || { echo "bad tarball"; exit 1; }
  tar xjf "$TMP/phpbb.tar.bz2" -C "$TMP"
  cp -a "$TMP"/phpBB3/. "$DOC/"
  mysql -uroot <<<"CREATE DATABASE IF NOT EXISTS \`$DB\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci; CREATE USER IF NOT EXISTS '$DBU'@'localhost' IDENTIFIED BY '$DBP'; GRANT ALL PRIVILEGES ON \`$DB\`.* TO '$DBU'@'localhost'; GRANT USAGE ON *.* TO '$DBU'@'localhost' WITH $DB_CAPS; FLUSH PRIVILEGES;"
  # pre-fill DB credentials; NO installed flag so the web installer completes setup
  cat > "$DOC/config.php" <<EOF
<?php
// phpBB auto-generated by KarnakPanel — installer continues from these values
\$dbms = 'phpbb\\\\db\\\\driver\\\\mysqli';
\$dbhost = 'localhost';
\$dbport = '';
\$dbname = '$DB';
\$dbuser = '$DBU';
\$dbpasswd = '$DBP';
\$table_prefix = 'phpbb_';
\$phpbb_adm_relative_path = 'adm/';
\$acm_type = 'phpbb\\\\cache\\\\driver\\\\file';
EOF
  chown -R "$U:" "$DOC"
  find "$DOC" -type d -exec chmod 755 {} + 2>/dev/null
  find "$DOC" -type f -exec chmod 644 {} + 2>/dev/null
  chmod 640 "$DOC/config.php"
  if command -v setfacl >/dev/null 2>&1; then setfacl -R -m u:nobody:rX "$DOC" 2>/dev/null || true; fi
  mysql -uroot skypanel -e "INSERT INTO mysql_dbs(user_id,db_name,db_user) VALUES($UIDN,'$DB','$DBU');" 2>/dev/null || echo "WARN: db tracking row not recorded"
  mysql -uroot skypanel -e "INSERT INTO site_installs(user_id,domain_id,app,path,url,version) VALUES($UIDN,$DID,'phpbb','$SUB','$URL','ready');" 2>/dev/null || echo "WARN: install not registered"
  echo "installed phpBB $VER at $URL (db $DB) — finish at $URL/install"
) &
echo "install started in background — watch Logs → software"
